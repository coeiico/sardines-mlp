"""
Draw the n = 2, m = 1 phase diagrams for phase.tex: build/phase-<which>.tex and build/phase-values.tex.

One cell per grid point, spanning halfway (in log space) to its neighbours: blank where the
extra feature is not learned, back-hatched where it takes the dimension, spot hatching where
the two share it as an antipodal pair. `majority` fills each cell with the phase most seeds
reach and dots the cells where they disagree; `lowest` with the phase of the seed whose loss
is lowest there. Layout only; the numbers are data/phase-cells.csv, from runs
phase-relu-seed0 to seed4.
"""

import csv
import math

with open('data/phase-cells.csv') as f:
  cells = list(csv.DictReader(f))

STYLE = {
  'not learned': None,
  'dedicated': 'hatch back=ink!45',
  'superposition': 'hatch=spot!80',
  'other': 'crosshatch=faint',
}


def edges(values: list[float]) -> dict[float, tuple[float, float]]:
  """Each value's cell: from the log-midpoint with its lower neighbour to that with its upper one."""
  logs = sorted(math.log10(v) for v in values)
  step = logs[1] - logs[0]
  return {10 ** x: (10 ** (x - step / 2), 10 ** (x + step / 2)) for x in logs}


density = edges(sorted({float(c['density']) for c in cells}))
relative = edges(sorted({float(c['relative_importance']) for c in cells}))


def span(table: dict[float, tuple[float, float]], value: float) -> tuple[float, float]:
  return table[min(table, key=lambda v: abs(math.log10(v) - math.log10(value)))]


for which, column in (('majority', 'majority'), ('lowest', 'lowest_loss_phase')):
  out = []
  for c in cells:
    style = STYLE[c[column]]
    x0, x1 = span(relative, float(c['relative_importance']))
    y0, y1 = span(density, float(c['density']))
    if style:
      out.append(f'\\fill[{style}] (axis cs:{x0:.6g},{y0:.6g}) rectangle (axis cs:{x1:.6g},{y1:.6g});')
  if which == 'majority':
    for c in cells:
      if float(c['agreement']) < 1:
        x, y = float(c['relative_importance']), float(c['density'])
        out.append(f'\\node[circle, fill=ink, inner sep=0pt, minimum size=1.5pt] at (axis cs:{x:.6g},{y:.6g}) {{}};')
  with open(f'build/phase-{which}.tex', 'w') as f:
    f.write('\n'.join(out) + '\n')

seeds = sum(int(cells[0][k]) for k in ('not_learned', 'dedicated', 'superposition', 'other'))
counts = {p: sum(c['majority'] == p for c in cells) for p in STYLE}
lowest = {p: sum(c['lowest_loss_phase'] == p for c in cells) for p in STYLE}
with open('build/phase-values.tex', 'w') as f:
  f.write(
    '% Generated by src/phase.py from data/; do not edit.\n'
    f'\\def\\nCells{{{len(cells)}}}\\def\\nSeeds{{{seeds}}}'
    f'\\def\\nSuper{{{counts["superposition"]}}}\\def\\nDedicated{{{counts["dedicated"]}}}'
    f'\\def\\nNotLearned{{{counts["not learned"]}}}\\def\\nOther{{{counts["other"]}}}'
    f'\\def\\nSplit{{{sum(float(c["agreement"]) < 1 for c in cells)}}}'
    f'\\def\\nSuperLowest{{{lowest["superposition"]}}}\\def\\nDedicatedLowest{{{lowest["dedicated"]}}}\n'
  )
