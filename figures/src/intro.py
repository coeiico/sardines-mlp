"""
Draw WᵀW and b as grids of signed cells for intro.tex: build/intro-<model>-<k>.tikz.

One cell per entry, shaded ink for negative values, spot for positive, white at 0 (the
SIGNED map of figure-design.md), clamped at ±1. The b strip sits under its matrix. Layout
only; the numbers are data/intro-wtw-<model>-seed0.npz from runs intro-relu-seed0 and
intro-linear-seed0.
"""

import csv

import numpy as np

# Instances drawn: (model, instance index into the 7 sparsities).
PANELS = [('linear', 6), ('relu', 0), ('relu', 2), ('relu', 4), ('relu', 6)]
GAP = 0.8  # cells between the matrix and the b strip


def shade(value: float) -> str:
  v = max(-1.0, min(1.0, value))
  strength = round(100 * abs(v))
  if strength < 3:
    return ''
  return f'spot!{strength}' if v > 0 else f'ink!{strength}'


def grid(wtw: np.ndarray, b: np.ndarray) -> str:
  n = wtw.shape[0]
  out = []
  for i in range(n):
    for j in range(n):
      colour = shade(float(wtw[i, j]))
      if colour:
        out.append(f'\\fill[{colour}] ({j},{n - 1 - i}) rectangle ++(1,1);')
  y = -1 - GAP
  for j in range(n):
    colour = shade(float(b[j]))
    if colour:
      out.append(f'\\fill[{colour}] ({j},{y}) rectangle ++(1,1);')
  out.append(f'\\mgrid{{(0,0)}}{{({n},{n})}}')
  out.append(f'\\mgrid{{(0,{y})}}{{({n},{y + 1})}}')
  return '\n'.join(out) + '\n'


mats = {model: np.load(f'data/intro-wtw-{model}-seed0.npz') for model in ('relu', 'linear')}
with open('data/intro-losses.csv') as f:
  rows = list(csv.DictReader(f))
for model, k in PANELS:
  with open(f'build/intro-{model}-{k}.tikz', 'w') as f:
    f.write(grid(mats[model]['wtw'][k], mats[model]['b'][k]))

# Quoted numbers: the density of each panel and seed 0's represented count there, and the
# range of represented counts over seeds at the sparsest setting.
lines = ['% Generated by src/intro.py from data/; do not edit.']
for i, (model, k) in enumerate(PANELS):
  row = rows[k]
  letter = 'abcde'[i]
  lines.append(f'\\def\\density{letter.upper()}{{{float(row["density"]):.2g}}}'
               f'\\def\\count{letter.upper()}{{{row[f"{model}_represented_seed0"]}}}')
sparsest = [int(rows[-1][f'relu_represented_seed{s}']) for s in range(5)]
lines.append(f'\\def\\sparsestMin{{{min(sparsest)}}}\\def\\sparsestMax{{{max(sparsest)}}}')
with open('build/intro-values.tex', 'w') as f:
  f.write('\n'.join(lines) + '\n')
