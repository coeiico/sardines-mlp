"""
Draw W's columns in the plane for polygons.tex: build/polygons-<i>.tikz and build/polygons-shapes.tikz.

Each panel overlays all five seeds at one density. A solution is only defined up to rotation
and reflection (any orthogonal Q gives the same WᵀW), so each seed is put in a canonical
pose first: its longest column along +x, and reflected so the next column round the circle
turns anticlockwise. Seed 0 is drawn as ink arrows, seeds 1 to 4 as faint ones. The shape
strip writes, for every seed and density, how many features are represented, in spot when
they form a regular polygon. Layout only; the numbers are data/polygons-columns-seed<s>.csv
and data/polygons-shapes.csv, from runs polygons-relu-seed0 to seed4.
"""

import csv
import math
from collections import Counter

SEEDS = range(5)
PANELS = [0, 2, 5, 8, 11, 13, 20]  # instance indices: densities 1 down to 0.01
SCALE = 1.0  # TikZ units per unit of weight


def read(path: str) -> list[dict[str, str]]:
  with open(path) as f:
    return list(csv.DictReader(f))


def canonical(points: list[tuple[float, float]]) -> list[tuple[float, float]]:
  norms = [math.hypot(x, y) for x, y in points]
  top = max(range(len(points)), key=norms.__getitem__)
  turn = -math.atan2(points[top][1], points[top][0])
  c, s = math.cos(turn), math.sin(turn)
  rotated = [(c * x - s * y, s * x + c * y) for x, y in points]
  # Reflect so the represented column with the smallest positive angle is above the x-axis.
  angles = [math.atan2(y, x) % (2 * math.pi) for x, y in rotated]
  shown = [a for a, n in zip(angles, norms, strict=True) if n > 0.5 and a > 1e-6]
  if shown and min(shown) > math.pi:
    rotated = [(x, -y) for x, y in rotated]
  return rotated


columns = {s: read(f'data/polygons-columns-seed{s}.csv') for s in SEEDS}
shapes = read('data/polygons-shapes.csv')
densities = sorted({float(r['density']) for r in shapes}, reverse=True)

for i, k in enumerate(PANELS):
  out = ['\\draw[level line] (0,0) circle (1);']
  for s in reversed(list(SEEDS)):  # seed 0 last, on top
    points = canonical([(float(r['x']), float(r['y'])) for r in columns[s] if int(r['instance']) == k])
    style = 'draw=ink, line width=0.6pt, -{Latex[length=1.4mm, width=1mm]}' if s == 0 else 'draw=faint, line width=0.35pt'
    for x, y in points:
      if math.hypot(x, y) > 0.05:
        out.append(f'\\draw[{style}] (0,0) -- ({SCALE * x:.4f},{SCALE * y:.4f});')
  with open(f'build/polygons-{i}.tikz', 'w') as f:
    f.write('\n'.join(out) + '\n')

# The shape strip: one column per density, one row per seed.
out = []
for j, d in enumerate(densities):
  for s in SEEDS:
    row = next(r for r in shapes if int(r['seed']) == s and float(r['density']) == d)
    colour = 'spot' if row['regular'] == 'True' and row['k'] == '5' else ('ink' if row['regular'] == 'True' else 'faint')
    out.append(f'\\node[font=\\footnotesize, text={colour}] at ({j},{-s}) {{{row["k"]}}};')
with open('build/polygons-shapes.tikz', 'w') as f:
  f.write('\n'.join(out) + '\n')

lines = ['% Generated by src/polygons.py from data/; do not edit.']
for i, k in enumerate(PANELS):
  d = densities[k]
  found = Counter((r['k'], r['regular']) for r in shapes if float(r['density']) == d)
  (kind, regular), count = found.most_common(1)[0]
  name = {'2': 'pair', '3': 'triangle', '4': 'square', '5': 'pentagon'}[kind] if regular == 'True' else f'{kind} features'
  letter = 'ABCDEFG'[i]
  lines.append(f'\\def\\density{letter}{{{d:.2g}}}\\def\\shape{letter}{{{name}}}\\def\\shapeCount{letter}{{{count}}}')
first = min(densities.index(d) for d in densities
            if all(r['k'] == '5' and r['regular'] == 'True' for r in shapes if float(r['density']) == d)
            and all(all(r['k'] == '5' and r['regular'] == 'True' for r in shapes if float(r['density']) == e) for e in densities if e <= d))
lines.append(f'\\def\\allPentagons{{{densities[first]:.2g}}}\\def\\nDensities{{{len(densities)}}}')
with open('build/polygons-values.tex', 'w') as f:
  f.write('\n'.join(lines) + '\n')
