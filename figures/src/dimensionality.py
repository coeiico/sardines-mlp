"""
Split the dimensionality data for dimensionality.tex into what pgfplots draws.

- build/dim-curve-<model>-seed<s>.csv: one seed's dimensions per feature against 1/(1 − S).
- build/dim-points.csv: every represented feature's Dᵢ, from all seeds, with duplicates at
  the drawn resolution (0.004 in Dᵢ) merged, so tens of thousands of points become a few
  thousand marks that look the same.
- build/dim-values.tex: quoted numbers.

Layout only; the numbers are data/dimensionality-curves.csv and
data/dimensionality-features.csv, from runs dimensionality-relu-seed0 to seed4 and
dimensionality-linear-seed0 to seed4.
"""

import csv

with open('data/dimensionality-curves.csv') as f:
  curves = list(csv.DictReader(f))
with open('data/dimensionality-features.csv') as f:
  features = list(csv.DictReader(f))

seeds = sorted({int(r['seed']) for r in curves})
for model in ('relu', 'linear'):
  for s in seeds:
    rows = [r for r in curves if r['model'] == model and int(r['seed']) == s]
    with open(f'build/dim-curve-{model}-seed{s}.csv', 'w') as f:
      f.write('x,y\n')
      f.writelines(f'{1 / float(r["density"]):.6g},{float(r["dimensions_per_feature"]):.6g}\n' for r in rows)

points = {(round(1 / float(r['density']), 4), round(float(r['dimensionality']) / 0.004) * 0.004) for r in features}
with open('build/dim-points.csv', 'w') as f:
  f.write('x,y\n')
  f.writelines(f'{x:.6g},{y:.4f}\n' for x, y in sorted(points))

# How many sparsity settings sit on the ½ plateau, per seed.
half = [sum(abs(float(r['dimensions_per_feature']) - 0.5) < 0.02 for r in curves if r['model'] == 'relu' and int(r['seed']) == s)
        for s in seeds]
with open('build/dim-values.tex', 'w') as f:
  f.write('% Generated by src/dimensionality.py from data/; do not edit.\n'
          f'\\def\\nSeeds{{{len(seeds)}}}\\def\\halfMin{{{min(half)}}}\\def\\halfMax{{{max(half)}}}'
          f'\\def\\nFeatures{{{len(features)}}}\n')
